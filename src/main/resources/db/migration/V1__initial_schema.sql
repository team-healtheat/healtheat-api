-- Source: Notion 01 data model and DB constraint implementation notes.
-- Unspecified business fields remain nullable; further rules require a decision.
CREATE TABLE users (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email text NOT NULL UNIQUE, password_hash text NOT NULL,
 age integer, gender text, role text NOT NULL DEFAULT 'USER',
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE user_preferences (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL UNIQUE REFERENCES users(id), allow_dining_out boolean,
 liked_foods jsonb, disliked_foods jsonb, dietary_preferences jsonb
);
CREATE TABLE user_allergies (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES users(id), allergen_name text, status text
);
CREATE TABLE health_factors (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code text UNIQUE, name text, type text, supported text
);
CREATE TABLE user_health_factors (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES users(id), health_factor_id bigint NOT NULL REFERENCES health_factors(id),
 reported_status text, original_text text, is_active boolean,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE meal_plans (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES users(id), plan_date date NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(), UNIQUE(user_id, plan_date)
);
CREATE TABLE meal_recommendations (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 meal_plan_id bigint NOT NULL REFERENCES meal_plans(id), meal_type text NOT NULL,
 source_type text, recommendation_reason text, is_current boolean NOT NULL DEFAULT true,
 version integer NOT NULL DEFAULT 1, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX meal_recommendations_current_unique ON meal_recommendations(meal_plan_id, meal_type) WHERE is_current = true;
CREATE TABLE meal_items (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 meal_recommendation_id bigint NOT NULL REFERENCES meal_recommendations(id),
 food_name text, food_role text, preparation_type text, serving_description text
);
CREATE TABLE recipes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 meal_item_id bigint NOT NULL UNIQUE REFERENCES meal_items(id), title text, servings integer, cooking_time_minutes integer
);
CREATE TABLE recipe_ingredients (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 recipe_id bigint NOT NULL REFERENCES recipes(id), ingredient_name text, quantity numeric, unit text
);
CREATE TABLE recipe_steps (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 recipe_id bigint NOT NULL REFERENCES recipes(id), step_number integer NOT NULL, instruction text,
 UNIQUE(recipe_id, step_number)
);
CREATE TABLE meal_records (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES users(id), meal_date date, meal_type text, source_type text,
 from_recommendation boolean, recommendation_id bigint REFERENCES meal_recommendations(id),
 created_at timestamptz NOT NULL DEFAULT now()
);
-- Only recommendation-based records participate; direct records remain unrestricted.
CREATE UNIQUE INDEX meal_records_recommendation_unique ON meal_records(recommendation_id) WHERE recommendation_id IS NOT NULL;
CREATE TABLE meal_record_items (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 meal_record_id bigint NOT NULL REFERENCES meal_records(id), food_name text, serving_description text
);
CREATE TABLE chat_sessions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES users(id), created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE chat_messages (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 chat_session_id bigint NOT NULL REFERENCES chat_sessions(id), role text, content text, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE pending_actions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES users(id), action_type text, payload jsonb, status text,
 created_at timestamptz NOT NULL DEFAULT now(), confirmed_at timestamptz
);
